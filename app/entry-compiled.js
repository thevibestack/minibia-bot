'use strict';

/**
 * Compiled-binary entry (REQ-07, task 6.3) — the `bun build --compile`
 * target used by tools/build-app.js.
 *
 * Two jobs:
 *  1. ASSETS (REQ-07): imports catalog.json + npcTrades.json so Bun embeds
 *     them into the single binary, and exposes them on
 *     globalThis.__MB_BUNDLED_ASSETS — app/catalog.ts resolves offline
 *     lookups from there (fs remains the dev/tests fallback; Bun also
 *     embeds the project tree's files as a virtual FS, so the panel's
 *     static serving and the fs asset path keep working in the binary).
 *  2. BOOT: calls runMain (the app lifecycle: dedicated Chrome launch /
 *     target scan, attach+inject, control panel on 127.0.0.1) and prints
 *     the panel URL when the server is ready.
 *
 * Bun-only by design (requires ./main.ts); Node cannot execute this file —
 * the build tool (tools/build-app.js) is what invokes Bun.
 */

const main = require('./main.ts');
const catalog = require('./assets/catalog.json');
const npcTrades = require('./assets/npcTrades.json');
const characters = require('./store/characters.ts');
const fs = require('node:fs');
const path = require('node:path');

if (typeof globalThis !== 'undefined') {
  globalThis.__MB_BUNDLED_ASSETS = {
    'catalog.json': catalog,
    'npcTrades.json': npcTrades,
  };
}

// REQ-04: the in-page agent bundle (generated by tools/build-agent.js) is
// embedded into the binary via Bun's virtual FS (same mechanism as the
// panel assets). Resolve it from the project root; Bun embeds the tree of
// the entry, so the fs read resolves offline inside the binary.
function resolveAgentBundle() {
  const candidates = [
    path.join(__dirname, '..', 'minibia-desktop-agent.js'),
    path.join(process.cwd(), 'minibia-desktop-agent.js'),
    path.join(__dirname, 'minibia-desktop-agent.js'),
  ];
  for (const candidate of candidates) {
    try {
      const source = fs.readFileSync(candidate, 'utf8');
      if (source && source.length > 0) return source;
    } catch (e) { /* try next candidate */ }
  }
  throw new Error('minibia-desktop-agent.js bundle not found (build input missing)');
}

// Per-character store adapter: the panel server calls loadCharacter({name})
// / saveCharacter({name, config}); app/store/characters.ts needs baseDir.
// listCharacters() powers the REQ-27 cross-load profiles list (slice 1b).
const baseDir = characters.storeBaseDir();
const store = {
  loadCharacter: ({ name }) => characters.loadCharacter({ baseDir, name }),
  saveCharacter: ({ name, config }) => characters.saveCharacter({ baseDir, name, config }),
  listCharacters: () => characters.listCharacters(baseDir),
};

// Surface re-establish probe: truthy once the injected agent bundle is
// alive in the current document (gameClient may still be booting — the
// identity endpoint reports null until the client is ready, REQ-02).
const PROBE_EXPRESSION = 'window.__mbAgent && typeof window.__mbAgent.readStats === "function" ? true : false';

main.runMain({
  panel: true,
  store,
  injectionSource: resolveAgentBundle(),
  probeExpression: PROBE_EXPRESSION,
  onState: (s) => {
    if (s.phase === 'panel-ready') {
      // eslint-disable-next-line no-console
      console.log('[minibia-desktop-bot] control panel: ' + s.url);
    }
  },
}).then((handle) => {
  if (!handle.session) {
    // eslint-disable-next-line no-console
    console.error('[minibia-desktop-bot] no game target found — launch and scan both failed. '
      + 'Make sure minibia.com/play is reachable and no Cloudflare challenge is blocking the window.');
    process.exit(1);
  }
  // Keep running: the Chrome child + panel server hold the event loop.
}).catch((err) => {
  // eslint-disable-next-line no-console
  console.error('[minibia-desktop-bot] startup failed: ' + (err && err.message ? err.message : err));
  process.exit(1);
});
